// generate_vk_rs.js — emit vk_dropin.rs: the real withdraw-circuit
// verifying key as Rust constants, formatted for a literal paste into
// program/src/vk.rs per that file's own DROP-IN INSTRUCTIONS:
//   1. Replace VK_ALPHA_G1 / VK_BETA_G2 / VK_GAMMA_G2 / VK_DELTA_G2 / VK_IC
//      with the arrays in vk_dropin.rs (same layout: big-endian limbs,
//      G2 limbs c1||c0 per 64-byte half — groth16-solana / snarkjs format).
//   2. Set VK_IS_PLACEHOLDER to false.
//   3. Nothing else changes.
// Source of truth: keys/verification_key.json (snarkjs export of the zkey).
const fs = require("fs");
const path = require("path");
const conv = require("./convert");

const zkDir = path.join(__dirname, "..");
const vk = JSON.parse(fs.readFileSync(path.join(zkDir, "keys", "verification_key.json"), "utf8"));
const sol = conv.vkToSolana(vk);

function fmtArray(hex, indent) {
  const bytes = Buffer.from(hex, "hex");
  const lines = [];
  for (let i = 0; i < bytes.length; i += 16) {
    const chunk = Array.from(bytes.subarray(i, i + 16)).join(", ");
    lines.push(indent + chunk + ",");
  }
  return lines.join("\n");
}

const icBlocks = sol.vk_ic
  .map(
    (hex) =>
      "    [\n" + fmtArray(hex, "        ") + "\n    ]"
  )
  .join(",\n");

const rs = `//! REAL withdraw-circuit verifying key — generated by the ZK track.
//! Source: zk/keys/verification_key.json (snarkjs export of withdraw.zkey).
//! These are DEV-CEREMONY keys (single local contributor, phase 1 + phase 2
//! run on one VM). Production requires an MPC ceremony; see zk/README.md.
//!
//! Drop into program/src/vk.rs per its header instructions: replace the five
//! constants below and set VK_IS_PLACEHOLDER to false. Nothing else changes.
//! Layout: big-endian limbs; G2 = x_c1||x_c0||y_c1||y_c0 (groth16-solana /
//! alt_bn128 precompile order). Public inputs: [root, nf, recipient, amount],
//! so VK_IC has 4 + 1 = 5 points.

pub const VK_IS_PLACEHOLDER: bool = false;

pub const VK_ALPHA_G1: [u8; 64] = [
${fmtArray(sol.vk_alpha_g1, "    ")}
];

pub const VK_BETA_G2: [u8; 128] = [
${fmtArray(sol.vk_beta_g2, "    ")}
];

pub const VK_GAMMA_G2: [u8; 128] = [
${fmtArray(sol.vk_gamma_g2, "    ")}
];

pub const VK_DELTA_G2: [u8; 128] = [
${fmtArray(sol.vk_delta_g2, "    ")}
];

pub const VK_IC: [[u8; 64]; ${sol.vk_ic.length}] = [
${icBlocks},
];
`;

const outPath = path.join(zkDir, "vk_dropin.rs");
fs.writeFileSync(outPath, rs);
console.log("wrote", outPath, rs.length, "bytes; IC points:", sol.vk_ic.length);
